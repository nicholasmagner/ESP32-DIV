#!/usr/bin/env python3
"""Regenerate embedded startup assets: python3 tools/generate_startup_assets.py."""
from pathlib import Path
from PIL import Image, ImageOps, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/startup'
OUT = ROOT / 'ESP32-DIV'

def array(name, values, kind='uint8_t', columns=16):
    digits = 4 if kind == 'uint16_t' else 2
    lines = [f'const {kind} {name}[] PROGMEM = {{']
    for i in range(0, len(values), columns):
        lines.append('  ' + ', '.join(f'0x{v:0{digits}x}' for v in values[i:i+columns]) + ',')
    return '\n'.join(lines + ['};', ''])

animation = Image.open(ASSETS / 'skull.gif')
assert animation.size == (100, 120) and animation.n_frames == 10
parts = ['// Generated by tools/generate_startup_assets.py; do not edit.', '#include "StartupAssets.h"', '']
durations = []
for i, frame in enumerate(ImageSequence.Iterator(animation)):
    durations.append(frame.info['duration'])
    frame = frame.convert('L')
    data = []
    for y in range(120):
        for bx in range(13):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x < 100 and frame.getpixel((x, y)) >= 128:
                    byte |= 0x80 >> bit
            data.append(byte)
    assert len(data) == 1560
    parts.append(array(f'skullFrame{i}', data))
parts.append('const uint8_t* const skullFrames[10] = {' + ', '.join(f'skullFrame{i}' for i in range(10)) + '};')
parts.append('const uint16_t skullDurations[10] = {' + ', '.join(map(str, durations)) + '};')
source = Image.open(ASSETS / 'liberty.png').convert('RGBA')
background = Image.new('RGBA', source.size, (0, 0, 0, 255))
background.alpha_composite(source)
logo = ImageOps.contain(background.convert('RGB'), (240, 300), Image.Resampling.LANCZOS)
canvas = Image.new('RGB', (240, 300), 'black')
canvas.paste(logo, ((240-logo.width)//2, (300-logo.height)//2))
values = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r,g,b in canvas.getdata()]
parts.append(array('libertyLogo', values, 'uint16_t', 12))
(OUT / 'StartupAssets.cpp').write_text('\n'.join(parts))
(OUT / 'StartupAssets.h').write_text('''#pragma once
#include <Arduino.h>
extern const uint8_t* const skullFrames[10];
extern const uint16_t skullDurations[10];
extern const uint16_t libertyLogo[240 * 300] PROGMEM;
''')
print(f'Generated 10 frames ({sum(durations)} ms) and 240x300 RGB565 logo.')
